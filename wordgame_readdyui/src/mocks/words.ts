export function getWordsByGame(gameId: string): WordEntry[] {
  switch (gameId) {
    case 'body-talk':
      return bodyTalkWords;
    case 'silent-shout':
      return silentShoutWords;
    case 'telestration':
      return telestrationWords;
    default:
      return [];
  }
}

export function getWordsByDifficulty(words: WordEntry[], difficulty: Difficulty | 'all'): WordEntry[] {
  if (difficulty === 'all') return words;
  return words.filter((w) => w.difficulty === difficulty);
}

export function getMaxWordCount(words: WordEntry[], difficulty: Difficulty | 'all'): number {
  return getWordsByDifficulty(words, difficulty).length;
}

export function pickRandomWords(words: WordEntry[], difficulty: Difficulty | 'all', count: number): string[] {
  const filtered = getWordsByDifficulty(words, difficulty);
  const shuffled = [...filtered].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length)).map((w) => w.word);
}

export interface DifficultyCounts {
  easy: number;
  medium: number;
  hard: number;
}

export function pickRandomWordsMixed(words: WordEntry[], counts: DifficultyCounts): string[] {
  const result: string[] = [];

  const easyWords = words.filter((w) => w.difficulty === 'easy');
  const mediumWords = words.filter((w) => w.difficulty === 'medium');
  const hardWords = words.filter((w) => w.difficulty === 'hard');

  const shuffledEasy = [...easyWords].sort(() => Math.random() - 0.5);
  const shuffledMedium = [...mediumWords].sort(() => Math.random() - 0.5);
  const shuffledHard = [...hardWords].sort(() => Math.random() - 0.5);

  result.push(...shuffledEasy.slice(0, counts.easy).map((w) => w.word));
  result.push(...shuffledMedium.slice(0, counts.medium).map((w) => w.word));
  result.push(...shuffledHard.slice(0, counts.hard).map((w) => w.word));

  return result.sort(() => Math.random() - 0.5);
}

export function getDifficultyCounts(words: WordEntry[]): DifficultyCounts {
  return {
    easy: words.filter((w) => w.difficulty === 'easy').length,
    medium: words.filter((w) => w.difficulty === 'medium').length,
    hard: words.filter((w) => w.difficulty === 'hard').length,
  };
}

